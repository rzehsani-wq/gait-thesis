# src/datasets/splits.py
"""
Subject-disjoint train/val/test split for CASIA-B.

The split was originally generated by

    rng = np.random.RandomState(42)
    shuffled = list(range(1, 125))
    rng.shuffle(shuffled)
    TEST, VAL, TRAIN = sorted(shuffled[:10]), sorted(shuffled[10:25]), sorted(shuffled[25:])

using numpy version [YOUR VERSION HERE]. To avoid numpy-version dependence,
the resulting subject IDs are hardcoded here.

Split rationale:
- 99 training subjects: fine-tuning + CASIA-SSL retraining (Butler Item 2)
- 15 validation subjects: checkpoint selection
- 10 test subjects: final reporting, unused during training or selection

The split is fixed across all run seeds (0, 1, 2). This differs from the
pre-revision protocol, where each seed resampled evaluation subjects.
"""

TEST_SUBJECTS = frozenset([25, 41, 56, 73, 76, 78, 80, 81, 100, 110])
VAL_SUBJECTS  = frozenset([2, 5, 8, 12, 17, 19, 31, 37, 43, 63, 67, 83, 91, 108, 114])
TRAIN_SUBJECTS = frozenset(range(1, 125)) - TEST_SUBJECTS - VAL_SUBJECTS

# Reproducibility assertions - fail fast if anything is off
assert len(TEST_SUBJECTS) == 10, f"Expected 10 test subjects, got {len(TEST_SUBJECTS)}"
assert len(VAL_SUBJECTS) == 15, f"Expected 15 val subjects, got {len(VAL_SUBJECTS)}"
assert len(TRAIN_SUBJECTS) == 99, f"Expected 99 train subjects, got {len(TRAIN_SUBJECTS)}"
assert TEST_SUBJECTS.isdisjoint(VAL_SUBJECTS), "Test and val overlap"
assert TEST_SUBJECTS.isdisjoint(TRAIN_SUBJECTS), "Test and train overlap"
assert VAL_SUBJECTS.isdisjoint(TRAIN_SUBJECTS), "Val and train overlap"
assert TEST_SUBJECTS | VAL_SUBJECTS | TRAIN_SUBJECTS == frozenset(range(1, 125)), \
    "Not all 124 subjects accounted for"
